import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { randomUUID } from "node:crypto";
import { allowedHosts, routeSources } from "./sources.js";

export interface SandboxCommand {
  label: string;
  executable: "openshell";
  args: string[];
}
export interface OpenShellTaskOptions {
  query: string;
  urls: string[];
  /** An already registered, authenticated gateway name; never a URL or SSH command. */
  gateway: string;
  image?: string;
  provider?: string;
  name?: string;
  directory?: string;
  maxSteps?: number;
  maxPages?: number;
  timeoutSeconds?: number;
  cpu?: number;
  memoryGiB?: number;
}
export interface OpenShellPlan {
  adapter: "openshell";
  specVersion: "v0.1.7";
  sandboxName: string;
  gateway: string;
  image: string;
  provider: string;
  directory: string;
  policyPath: string;
  policyYaml: string;
  commands: SandboxCommand[];
  inspectCommand: SandboxCommand;
  deleteCommand: SandboxCommand;
  limits: { timeoutSeconds: number; maxSteps: number; maxPages: number };
  secretMode: "gateway-provider-placeholder";
  validation: "plan-only";
}
export interface SandboxCommandResult {
  label: string;
  exitCode: number;
  stdout: string;
  stderr: string;
  termination?: "timeout" | "output_limit" | "aborted";
}
export interface OpenShellExecution {
  sandboxName: string;
  status: "completed" | "partial" | "failed" | "cancelled";
  commands: SandboxCommandResult[];
  artifactsDirectory: string;
  cleanupPolicy: "retain";
  /** No gateway state is inferred merely from a child process exit. */
  sandboxState: "unknown" | "created";
}
const NAME = /^[a-z][a-z0-9-]{0,62}$/;
function identifier(value: string, label: string) {
  if (!NAME.test(value)) throw new Error(`${label} must match ${NAME}`);
  return value;
}
function positive(value: number, label: string, maximum: number) {
  if (!Number.isSafeInteger(value) || value < 1 || value > maximum)
    throw new Error(`${label} must be an integer from 1 to ${maximum}`);
  return value;
}
function command(
  label: string,
  gateway: string,
  args: string[],
): SandboxCommand {
  return { label, executable: "openshell", args: ["-g", gateway, ...args] };
}
/** The generated policy is strict by host and binary. It never grants wildcard Internet access. */
export function openShellPolicy(hosts: string[]): string {
  if (!hosts.length)
    throw new Error("At least one public source host is required");
  // Reuse the public URL validator; untrusted text never becomes YAML syntax.
  const validated = [...new Set(hosts)].map(
    (host) =>
      new URL(routeSources("policy", [`https://${host}/`])[0]!.url).hostname,
  );
  return [
    "# Generated by web-harness-runtime; OpenShell policy schema v1 / CLI v0.1.7.",
    "version: 1",
    "filesystem_policy:",
    "  include_workdir: true",
    "  read_only: [/usr, /lib, /lib64, /etc, /opt/web-harness, /bin, /sbin, /sys, /dev]",
    "  read_write: [/workspace, /tmp, /home/node]",
    "landlock:",
    "  compatibility: hard_requirement",
    "process:",
    '  run_as_user: "1000"',
    '  run_as_group: "1000"',
    "network_policies:",
    "  research_pages:",
    "    endpoints:",
    ...validated.flatMap((host) => [
      `      - host: ${JSON.stringify(host)}`,
      "        port: 443",
      "        tls: skip",
    ]),
    "    binaries:",
    "      - path: /usr/lib/chromium/chromium",
    // Rust agent-browser may fetch a page; Node performs source DNS lookup.
    "      - path: /usr/local/bin/node",
    "",
    "# OpenRouter access/credential rewrite is supplied by the attached provider profile.",
    "# No package registry access at runtime: the image contains the agent and browser.",
    "# tls:skip permits HTTPS to source hosts, not HTTP-method inspection.",
    "",
  ].join("\n");
}
/** Pure dry-run: no gateway contact, secret reads, image build, or sandbox allocation. */
export function planOpenShellTask(
  options: OpenShellTaskOptions,
): OpenShellPlan {
  if (
    !options.query.trim() ||
    Buffer.byteLength(options.query) > 24_000 ||
    options.query.includes("\0")
  )
    throw new Error("Query must be nonempty and no more than 24KB");
  if (!options.urls.length || options.urls.length > 20)
    throw new Error("Specify 1–20 source URLs");
  const sources = routeSources(options.query, options.urls);
  const gateway = identifier(options.gateway, "gateway");
  const sandboxName = identifier(
    options.name ?? `research-${randomUUID().slice(0, 8)}`,
    "name",
  );
  const provider = identifier(
    options.provider ?? "web-harness-openrouter",
    "provider",
  );
  const image = options.image ?? "web-harness-runtime:local";
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._/:@-]{0,254}$/.test(image))
    throw new Error("Invalid OCI image reference");
  const limits = {
    maxSteps: positive(options.maxSteps ?? 70, "maxSteps", 1000),
    maxPages: positive(options.maxPages ?? 12, "maxPages", 100),
    timeoutSeconds: positive(
      options.timeoutSeconds ?? 600,
      "timeoutSeconds",
      7200,
    ),
  };
  const cpu = positive(options.cpu ?? 2, "cpu", 32);
  const memory = `${positive(options.memoryGiB ?? 4, "memoryGiB", 64)}Gi`;
  const directory = resolve(
    options.directory ?? join(".runtime", "sandbox-plans", sandboxName),
  );
  const policyPath = join(directory, "policy.yaml");
  const create = command("create-and-run", gateway, [
    "sandbox",
    "create",
    "--name",
    sandboxName,
    "--from",
    image,
    "--provider",
    provider,
    "--policy",
    policyPath,
    "--cpu",
    String(cpu),
    "--memory",
    memory,
    "--",
    "/usr/local/bin/node",
    "/opt/web-harness/dist/cli.js",
    "run",
    options.query,
    "--url",
    ...sources.map((source) => source.url),
    "--max-steps",
    String(limits.maxSteps),
    "--max-pages",
    String(limits.maxPages),
    "--timeout",
    String(limits.timeoutSeconds),
    "--json",
  ]);
  if (
    create.args.some((arg) => Buffer.byteLength(arg) > 32 * 1024) ||
    create.args.reduce((sum, arg) => sum + Buffer.byteLength(arg), 0) >
      256 * 1024
  )
    throw new Error("OpenShell command exceeds argument size limits");
  const download = command("download-artifacts", gateway, [
    "sandbox",
    "download",
    sandboxName,
    ".runtime",
    join(directory, "artifacts"),
  ]);
  return {
    adapter: "openshell",
    specVersion: "v0.1.7",
    sandboxName,
    gateway,
    image,
    provider,
    directory,
    policyPath,
    policyYaml: openShellPolicy(allowedHosts(sources)),
    commands: [create, download],
    inspectCommand: command("inspect", gateway, [
      "sandbox",
      "get",
      sandboxName,
      "--output",
      "json",
    ]),
    deleteCommand: command("delete", gateway, [
      "sandbox",
      "delete",
      sandboxName,
    ]),
    limits,
    secretMode: "gateway-provider-placeholder",
    validation: "plan-only",
  };
}
export async function writeOpenShellPlan(plan: OpenShellPlan) {
  await mkdir(plan.directory, { recursive: true, mode: 0o700 });
  await writeFile(plan.policyPath, plan.policyYaml, { mode: 0o600 });
  await writeFile(
    join(plan.directory, "plan.json"),
    JSON.stringify(plan, null, 2) + "\n",
    { mode: 0o600 },
  );
  return plan.directory;
}
function hostEnvironment(): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {};
  // The gateway already owns the credential. Do not pass .env API keys to this child.
  for (const key of [
    "PATH",
    "HOME",
    "XDG_CONFIG_HOME",
    "XDG_DATA_HOME",
    "TMPDIR",
    "LANG",
    "SYSTEMROOT",
    "SSL_CERT_FILE",
    "SSL_CERT_DIR",
  ]) {
    if (process.env[key]) env[key] = process.env[key];
  }
  return env;
}
export function runOpenShellCommand(
  command: SandboxCommand,
  options: {
    signal?: AbortSignal;
    timeoutMs?: number;
    killGraceMs?: number;
    maxOutputBytes?: number;
    onOutput?: (stream: "stdout" | "stderr", text: string) => void;
  } = {},
): Promise<SandboxCommandResult> {
  if (command.executable !== "openshell")
    throw new Error("Unsupported sandbox executable");
  const cap = options.maxOutputBytes ?? 16 * 1024 * 1024;
  const grace = options.killGraceMs ?? 2000;
  if (!Number.isSafeInteger(cap) || cap < 1 || cap > 16 * 1024 * 1024)
    throw new Error("Invalid output limit");
  if (!Number.isSafeInteger(grace) || grace < 1 || grace > 10_000)
    throw new Error("Invalid kill grace period");
  return new Promise((resolveResult, reject) => {
    if (options.signal?.aborted) {
      resolveResult({
        label: command.label,
        exitCode: 130,
        stdout: "",
        stderr: "",
        termination: "aborted",
      });
      return;
    }
    const child = spawn("openshell", command.args, {
      shell: false,
      env: hostEnvironment(),
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "",
      stderr = "",
      captured = 0,
      settled = false;
    let termination: SandboxCommandResult["termination"];
    let killTimer: ReturnType<typeof setTimeout> | undefined;
    let settleTimer: ReturnType<typeof setTimeout> | undefined;
    const cleanup = () => {
      clearTimeout(timer);
      if (killTimer) clearTimeout(killTimer);
      if (settleTimer) clearTimeout(settleTimer);
      options.signal?.removeEventListener("abort", abort);
    };
    const finish = (code: number | null) => {
      if (settled) return;
      settled = true;
      cleanup();
      const exitCode =
        termination === "timeout"
          ? 124
          : termination === "output_limit"
            ? 125
            : termination === "aborted"
              ? 130
              : (code ?? 1);
      resolveResult({
        label: command.label,
        exitCode,
        stdout,
        stderr,
        ...(termination ? { termination } : {}),
      });
    };
    const terminate = (
      reason: NonNullable<SandboxCommandResult["termination"]>,
    ) => {
      if (termination || settled) return;
      termination = reason;
      child.kill("SIGTERM");
      killTimer = setTimeout(() => {
        child.kill("SIGKILL");
        // A leaked grandchild can keep stdio open after the CLI dies. Bound local settlement too.
        settleTimer = setTimeout(() => {
          child.stdout.destroy();
          child.stderr.destroy();
          finish(null);
        }, 500);
      }, grace);
    };
    const abort = () => terminate("aborted");
    const timer = setTimeout(
      () => terminate("timeout"),
      options.timeoutMs ?? 60_000,
    );
    options.signal?.addEventListener("abort", abort, { once: true });
    const collect = (stream: "stdout" | "stderr", chunk: Buffer) => {
      if (settled || termination) return;
      const available = Math.max(0, cap - captured);
      const accepted = chunk.subarray(0, available);
      captured += accepted.length;
      const text = accepted.toString();
      if (stream === "stdout") stdout += text;
      else stderr += text;
      if (text) options.onOutput?.(stream, text);
      if (chunk.length > available) terminate("output_limit");
    };
    child.stdout.on("data", (data: Buffer) => collect("stdout", data));
    child.stderr.on("data", (data: Buffer) => collect("stderr", data));
    child.once("error", (error) => {
      if (settled) return;
      settled = true;
      cleanup();
      reject(error);
    });
    child.once("close", (code) => finish(code));
  });
}
/** Allocates a real sandbox only through this explicit host-side call. Never invoked by model tools. */
export async function executeOpenShellPlan(
  plan: OpenShellPlan,
  options: {
    confirmed: true;
    signal?: AbortSignal;
    onOutput?: (stream: "stdout" | "stderr", text: string) => void;
  },
): Promise<OpenShellExecution> {
  if (options.confirmed !== true)
    throw new Error("Explicit execution is required");
  await writeOpenShellPlan(plan);
  const commands: SandboxCommandResult[] = [];
  let status: OpenShellExecution["status"] = "failed";
  try {
    options.signal?.throwIfAborted();
    const create = await runOpenShellCommand(plan.commands[0]!, {
      ...options,
      timeoutMs: (plan.limits.timeoutSeconds + 300) * 1000,
    });
    commands.push(create);
    // Exit 2 is the runtime's partial answer. Other failures can still leave useful artifacts.
    status =
      create.termination === "aborted"
        ? "cancelled"
        : create.exitCode === 0
          ? "completed"
          : create.exitCode === 2
            ? "partial"
            : "failed";
    if (!options.signal?.aborted) {
      const download = await runOpenShellCommand(plan.commands[1]!, {
        ...options,
        timeoutMs: 90_000,
      });
      commands.push(download);
      if (download.exitCode !== 0)
        status = status === "completed" ? "partial" : "failed";
    }
  } catch (error) {
    status = options.signal?.aborted ? "cancelled" : "failed";
    commands.push({
      label: "adapter-error",
      exitCode: 1,
      stdout: "",
      stderr: error instanceof Error ? error.message : String(error),
    });
  }
  if (options.signal?.aborted) status = "cancelled";
  const execution: OpenShellExecution = {
    sandboxName: plan.sandboxName,
    status,
    commands,
    artifactsDirectory: join(plan.directory, "artifacts"),
    cleanupPolicy: "retain",
    sandboxState: commands.some(
      (c) => c.label === "download-artifacts" && c.exitCode === 0,
    )
      ? "created"
      : "unknown",
  };
  await writeFile(
    join(plan.directory, "execution.json"),
    JSON.stringify(execution, null, 2) + "\n",
    { mode: 0o600 },
  );
  return execution;
}
export async function doctorOpenShell(gateway?: string): Promise<{
  available: boolean;
  checks: SandboxCommandResult[];
  limitation?: string;
}> {
  const checks: SandboxCommandResult[] = [];
  try {
    const version = await runOpenShellCommand(
      { label: "version", executable: "openshell", args: ["--version"] },
      { timeoutMs: 10_000 },
    );
    checks.push(version);
    if (gateway) {
      identifier(gateway, "gateway");
      checks.push(
        await runOpenShellCommand(
          command("gateway-status", gateway, ["gateway", "info"]),
          { timeoutMs: 15_000 },
        ),
      );
    }
    return { available: checks.every((check) => check.exitCode === 0), checks };
  } catch (error) {
    return {
      available: false,
      checks,
      limitation: error instanceof Error ? error.message : String(error),
    };
  }
}
